import assert from 'node:assert/strict';
import './insights.js';
const {summarize}=globalThis.PhotoMemoryInsights;
const now=new Date('2026-10-10T15:00:00Z');
const history=[100,200,300,400].map(totalScore=>({totalScore}));
assert.equal(summarize([]).latest,null);
assert.equal(summarize(history).delta,200);
assert.equal(summarize(history).windowSize,2);
assert.equal(summarize(history).undated,4);
assert.equal(summarize(history,{days:30,now}).count,0);
assert.equal(summarize([{totalScore:0},{totalScore:null},{totalScore:-1},{totalScore:1300}]).count,1);
assert.equal(summarize(history.slice(0,3)).delta,null);
assert.equal(summarize(history,{now}).activeDays,0);
const dated=[{totalScore:200,completedAtUtc:now.toISOString()},{totalScore:300,completedAtUtc:now.toISOString()},{totalScore:400,completedAtUtc:'2026-10-11T00:00:00Z'}];
assert.equal(summarize(dated,{now}).activeDays,1);
assert.equal(summarize(dated,{now,days:30}).count,2);
assert.equal(summarize([{totalScore:0,completedAtUtc:'bad date'}]).undated,1);
const skills=history.map(t=>({...t,scores:[{category:'Visual Memory',score:170},{category:'Working Memory',score:20}]}));
assert.equal(summarize(skills).focus,null);
assert.equal(summarize(skills).skills[0].percent,50);
assert.equal(summarize(skills).skills[1].percent,null);
const complete=history.map(t=>({...t,scores:Object.entries(globalThis.PhotoMemoryInsights.SKILLS).map(([category,max])=>({category,score:category==='Working Memory'?20:max/2}))}));
assert.equal(summarize(complete).focus.name,'Working Memory');
console.log('PASS 15 progress assertions: trends, dates, missing data, score bounds and complete skill coverage');
